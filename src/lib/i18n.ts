export type StringKey = keyof typeof strings;

export function useT() {
  const lang = useStore((s) => s.lang);
  const t = (k: StringKey) => strings[k][lang];
  const name = (x: { name: string; nameTr: string } | undefined) => (x ? (lang === 'tr' ? x.nameTr : x.name) : '?');
  const nf = new Intl.NumberFormat(lang === 'tr' ? 'tr-TR' : 'en-US', { maximumFractionDigits: 2 });
  const num = (n: number) => nf.format(Math.abs(n) < 5e-5 ? 0 : n);
  return { t, name, num, lang };
}
